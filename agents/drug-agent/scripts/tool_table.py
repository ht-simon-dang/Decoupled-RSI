"""Regenerate the tool-pool table in ``docs/agent-tool-architecture.md``.

``tests/test_pools.py::test_the_architecture_document_matches_the_pools`` asserts two
things about that document: that it states the pool's size in the exact words
``"<n> tools, each with named operations"``, and that **every** ``tool_id`` in the pool
appears in the file verbatim. With nine tools those were prose commitments a person
could keep by hand. With the external catalogue they are not: a table of forty rows
maintained by hand is a table that is wrong within a week, and the test would then be
failing for a documentation reason rather than a code one.

So the table is generated, in the same spirit as the exported JSON schemas: the section
between the sentinels is rewritten from the live pool, and everything outside them is
prose that a person writes. The generator is the mechanism that keeps the assertion
honest rather than merely satisfied — the count and the ids come from
``tool_pool()`` itself, so there is nowhere for them to disagree.

Status is deliberately **not** written into the table. It is a fact about the machine
that ran this script, not about the repository, and committing "UNAVAILABLE" for a tool
that is available on a colleague's workstation would put a machine-specific claim into
version control. ``drugagent tools`` answers that question live.

    make tool-table
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TARGET = REPO / "docs" / "agent-tool-architecture.md"

BEGIN = "<!-- TOOL-TABLE-BEGIN — generated by scripts/tool_table.py; edit that, not this -->"
END = "<!-- TOOL-TABLE-END -->"


def render() -> str:
    """The generated block: the count sentence, then one row per tool."""
    sys.path.insert(0, str(REPO / "src"))
    from drug_agent.tools.registry import tool_pool

    tools = tool_pool()
    lines = [
        BEGIN,
        "",
        f"The pool is **{len(tools)} tools, each with named operations.** Those operation",
        'names are the keys the request journal meters under, so "what can this deployment',
        'do" and "what did it actually do" are answerable in one vocabulary.',
        "",
        "Status is not listed here: it is a fact about a machine, not about the repository.",
        "Run `drugagent tools` for this machine's answer, or `drugagent doctor` to see it",
        "coloured with the reason attached.",
        "",
        "| capability id | what it computes | backend it binds | operations |",
        "| ------------- | ---------------- | ---------------- | ---------- |",
    ]
    for card in tools:
        title = (card.title or card.tool_id).replace("|", "\\|")
        # An unavailable card names no backend, so fall back to what it *would* bind.
        binding = card.runtime_requirements.get("upstream") or ""
        binding = binding.rsplit("/", 1)[-1] if binding else (card.backend or "—")
        if binding == "none":
            binding = "—"
        operations = " · ".join(sorted(card.operations)) or "—"
        lines.append(f"| `{card.tool_id}` | {title} | {binding} | {operations} |")
    lines += ["", END]
    return "\n".join(lines)


def main() -> int:
    text = TARGET.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{TARGET}: missing the {BEGIN!r} / {END!r} sentinels")
    head, _, rest = text.partition(BEGIN)
    _, _, tail = rest.partition(END)
    updated = head + render() + tail
    if updated == text:
        print(f"{TARGET.name} is already current.")
        return 0
    TARGET.write_text(updated, encoding="utf-8")
    print(f"Rewrote the tool table in {TARGET.name}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
